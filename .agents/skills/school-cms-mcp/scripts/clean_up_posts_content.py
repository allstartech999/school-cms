    for item in CLEAN_POSTS:
        post_id = item["id"]
        try:
            c = SchoolCMSMCPClient()
            c.connect()
            res = c.call_tool('update_school_post', {
                'id_or_slug': post_id,
                'content': item["content"].strip()
            })
            text = res.get('result', {}).get('content', [{}])[0].get('text', '')
            print(f"Post {post_id} cleaned up: {text.replace(chr(10), ' ')}")
        except Exception as e:
            print(f"Post {post_id} error: {e}")
