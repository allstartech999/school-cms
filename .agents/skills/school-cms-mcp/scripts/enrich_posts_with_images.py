def fetch_photos_for_post(item):
    if "extra_images" in item:
        return item["extra_images"], False

    url = item.get("fb_url")
    if not url:
        # fetch canonical
        req = urllib.request.Request(f'https://www.facebook.com/{item["fb_id"]}', headers={'User-Agent': 'Mozilla/5.0 (Windows NT 10.0; Win64; x64)'})
        try:
            resp = urllib.request.urlopen(req)
            canon = resp.geturl()
            url = canon.replace('www.facebook.com', 'm.facebook.com')
        except Exception as e:
            print(f"Error getting canonical for {item['fb_id']}: {e}")
            return [], False

    m_req = urllib.request.Request(url, headers={'User-Agent': 'Mozilla/5.0 (Linux; Android 10; Mobile)'})
    try:
        m_resp = urllib.request.urlopen(m_req)
        html = m_resp.read().decode('utf-8', errors='ignore')
        raw_imgs = set(re.findall(r'src=\"(https://scontent[^\"]+)\"', html))
        valid = []
        for img in raw_imgs:
            clean = img.replace('&amp;', '&')
            if '572197027_1384045007066758' in clean or 's100x100' in clean or 's50x50' in clean:
                continue
            valid.append(clean)
        return valid, True
    except Exception as e:
        print(f"Error fetching mobile page for {url}: {e}")
        return [], False


def main():
    print("Connecting to School CMS MCP Server (Production)...")
    client = SchoolCMSMCPClient()
    client.connect()
    print("Connected successfully!\n")

    for item in POSTS_ENRICHMENT:
        post_id = item["id"]
        print(f"--- Processing Post ID {post_id}: {item['title'][:40]} ---")
        
        photos, need_upload = fetch_photos_for_post(item)
        print(f"   Found {len(photos)} photos")
        
        uploaded_urls = []
        captions = item.get("photo_captions", [])

        for idx, p_url in enumerate(photos):
            cap = captions[idx] if idx < len(captions) else f"ภาพบรรยากาศ {idx + 1}"
            if need_upload:
                try:
                    upload_res = client.call_tool('upload_media_by_url', {
                        'source_url': p_url,
                        'alt_text': cap,
                        'agent_name': 'Antigravity AI'
                    })
                    text_resp = upload_res.get('result', {}).get('content', [{}])[0].get('text', '')
                    m_url = re.search(r'URL:\s*([^\n\r]+)', text_resp)
                    if m_url:
                        u_path = m_url.group(1).strip()
                        uploaded_urls.append((u_path, cap))
                        print(f"   Uploaded: {u_path} ({cap[:30]})")
                    else:
                        print(f"   Upload failed: {text_resp[:80]}")
                except Exception as e:
                    print(f"   Upload exception: {e}")
            else:
                uploaded_urls.append((p_url, cap))

        # Build enhanced content with markdown image tags
        gallery_md = "\n\n"
        if uploaded_urls:
            gallery_md += "\n".join([f"![{cap}]({u})" for u, cap in uploaded_urls])
        else:
            # Fallback to post thumbnail
            gallery_md += f"![{item['title']}](/uploads/2026/10/1792902699757059925-ai.jfif)"

        fb_link_md = f"\n\n---\n*แหล่งที่มา: [เพจทางการโรงเรียนโพนงามพิทยานุกูล](https://www.facebook.com/phonngampittayanukul)*"
        full_content = item["base_content"] + gallery_md + fb_link_md

        # Update post in CMS
        update_args = {
            'id_or_slug': post_id,
            'content': full_content
        }
        update_res = client.call_tool('update_school_post', update_args)
        res_text = update_res.get('result', {}).get('content', [{}])[0].get('text', '')
        print(f"   Update result: {res_text.replace(chr(10), ' ')}")
        time.sleep(1.0)

    print("\n All 10 posts enriched with image galleries successfully!")


if __name__ == '__main__':
    main()
