def main():
    print(f"Connecting to School CMS MCP Server to update {len(POSTS)} posts...")
    for p in POSTS:
        pid = p['id']
        try:
            client = SchoolCMSMCPClient()
            client.connect()
            res = client.call_tool('update_school_post', {
                'id_or_slug': pid,
                'content': p['content']
            })
            text = res.get('result', {}).get('content', [{}])[0].get('text', '')
            print(f"[+] Post {pid} updated successfully: {text[:60]}")
        except Exception as e:
            print(f"[-] Post {pid} failed: {e}")
        time.sleep(0.5)

    print("\nAll posts updated with photo galleries successfully!")

if __name__ == '__main__':
    main()
